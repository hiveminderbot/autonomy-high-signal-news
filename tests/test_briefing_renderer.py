class TestTextRenderer:
    """Test TextRenderer."""
    
    @pytest.fixture
    def renderer(self):
        return TextRenderer()
    
    def test_render_header(self, renderer, sample_result):
        output = renderer.render(sample_result)
        assert 'MORNING BRIEFING' in output
        assert '=' * 40 in output or '=' * 50 in output
    
    def test_render_sections(self, renderer, sample_result):
        output = renderer.render(sample_result)
        assert 'AI' in output
        assert 'SOFTWARE' in output
    
    def test_render_tier_markers(self, renderer, sample_result):
        output = renderer.render(sample_result)
        assert '[MUST]' in output
        assert '[IMP]' in output
        assert '[CTX]' in output
    
    def test_render_urgency_markers(self, renderer, sample_result):
        output = renderer.render(sample_result)
        assert '[BREAKING]' in output
    
    def test_render_wraps_text(self, renderer, sample_result):
        output = renderer.render(sample_result)
        # Should not have extremely long lines
        lines = output.split('\n')
        for line in lines:
            assert len(line) <= 80  # Reasonable wrap width
    
    def test_wrap_text_method(self, renderer):
        long_text = "This is a very long sentence that should be wrapped at the appropriate width."
        wrapped = renderer._wrap_text(long_text, 30)
        lines = wrapped.split('\n')
        for line in lines:
            # Account for the "   " prefix added by _wrap_text
            assert len(line) <= 33  # 30 + 3 space prefix


