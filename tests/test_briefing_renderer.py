class TestRendererEdgeCases:
    """Test edge cases for renderers."""
    
    @pytest.fixture
    def empty_result(self):
        return BriefingResult(
            metadata=BriefingMetadata(
                generated_at="2024-01-01",
                total_stories=0,
                must_read_count=0,
                important_count=0,
                contextual_count=0,
                sources_used=0,
                reading_time_minutes=0
            ),
            sections=[]
        )
    
    def test_markdown_empty_sections(self, empty_result):
        renderer = MarkdownRenderer()
        output = renderer.render(empty_result)
        assert '0 stories' in output
        assert '0 sources' in output
    
    def test_html_empty_sections(self, empty_result):
        renderer = HTMLRenderer()
        output = renderer.render(empty_result)
        assert '<body>' in output
        assert '</body>' in output
    
    def test_text_empty_sections(self, empty_result):
        renderer = TextRenderer()
        output = renderer.render(empty_result)
        assert '0 stories' in output
    
    def test_story_without_url(self):
        """Test rendering a story without a URL."""
        result = BriefingResult(
            metadata=BriefingMetadata(
                generated_at="2024-01-01",
                total_stories=1,
                must_read_count=0,
                important_count=1,
                contextual_count=0,
                sources_used=1,
                reading_time_minutes=1
            ),
            sections=[
                BriefingSection(name='Test', emoji='🧪', stories=[{
                    'title': 'No URL Story',
                    'summary': 'This story has no URL.',
                    'sources': ['Source'],
                    'tier': 'important',
                    'entities': [],
                    'urgency': 'normal',
                }])
            ]
        )
        
        md = render_markdown(result)
        assert 'No URL Story' in md
        assert '](http' not in md  # Should not create empty link
        
        html = render_html(result)
        assert 'No URL Story' in html
        assert 'href=' not in html  # Should not have link


